# Motor de Inferencia
# -----------------------------------------------------------------------------
def run_daily_inference(file_path: str):
    if not os.path.exists(file_path):
        print(f"[ERROR] No se encontró el archivo de datos: {file_path}")
        sys.exit(1)

    print(f"Cargando series de mercado desde '{file_path}'...")
    df = pd.read_excel(file_path, sheet_name=SHEET_NAME)
    df["fecha"] = pd.to_datetime(df["fecha"])
    df = df.sort_values("fecha").reset_index(drop=True)
    df = df[df["fecha"] >= "2010-01-01"].copy().reset_index(drop=True)

    # Limpieza de feriados locales
    has_usdclp = df["USDCLP Curncy|PX_LAST"].notna()
    price_diff = df["USDCLP Curncy|PX_LAST"].diff()
    intraday_range = df["USDCLP Curncy|PX_HIGH"] - df["USDCLP Curncy|PX_LOW"]
    is_stale_holiday = (price_diff == 0) & (intraday_range == 0)

    cols_to_ffill = [c for c in df.columns if c != "fecha" and "FECHA_RELEASE" not in c]
    df[cols_to_ffill] = df[cols_to_ffill].ffill()
    df_clean = df[has_usdclp & (~is_stale_holiday)].copy().reset_index(drop=True)
    df_clean[cols_to_ffill] = df_clean[cols_to_ffill].ffill()

    # Construcción de variables y tasas
    ret_spot_log = np.log(df_clean["USDCLP Curncy|PX_LAST"] / df_clean["USDCLP Curncy|PX_LAST"].shift(1))
    target_y = (df_clean["USDCLP Curncy|PX_LAST"] > df_clean["USDCLP Curncy|PX_LAST"].shift(1)).astype(int)

    delta_days = df_clean["fecha"].diff().dt.days.clip(lower=1, upper=7).fillna(1.0)
    icp_raw_ret = df_clean["CLICP Index|PX_LAST"].pct_change() / delta_days
    tpm_daily = (df_clean["CHOVCHOV Index|PX_LAST"] / 100.0) / 360.0
    r_clp_1d = pd.Series(np.where((icp_raw_ret > 0) & (icp_raw_ret < 0.002), icp_raw_ret, tpm_daily), index=df_clean.index)

    usd_rate_annual = df_clean["SOFRRATE Index|PX_LAST"].combine_first(df_clean["FEDL01 Index|PX_LAST"])
    r_usd_1d = (usd_rate_annual / 100.0) / 360.0

    raw_feat = pd.DataFrame(index=df_clean.index)
    ret_zar = np.log(df_clean["USDZAR Curncy|PX_LAST"] / df_clean["USDZAR Curncy|PX_LAST"].shift(1))
    ret_mxn = np.log(df_clean["USDMXN Curncy|PX_LAST"] / df_clean["USDMXN Curncy|PX_LAST"].shift(1))
    ret_brl = np.log(df_clean["USDBRL Curncy|PX_LAST"] / df_clean["USDBRL Curncy|PX_LAST"].shift(1))
    em_basket = 0.40 * ret_zar + 0.35 * ret_mxn + 0.25 * ret_brl
    raw_feat["f1_em_divergence"] = em_basket - 0.35 * ret_spot_log

    ret_bbdxy = np.log(df_clean["BBDXY Index|PX_LAST"] / df_clean["BBDXY Index|PX_LAST"].shift(1))
    ret_dxy = np.log(df_clean["DXY Curncy|PX_LAST"] / df_clean["DXY Curncy|PX_LAST"].shift(1))
    usd_global = 0.60 * ret_bbdxy + 0.40 * ret_dxy
    raw_feat["f2_usd_divergence"] = usd_global - 0.35 * ret_spot_log

    ret_hg1 = np.log(df_clean["HG1 Comdty|PX_LAST"] / df_clean["HG1 Comdty|PX_LAST"].shift(1))
    ret_lme = np.log(df_clean["LMCADS03 Comdty|PX_LAST"] / df_clean["LMCADS03 Comdty|PX_LAST"].shift(1))
    raw_feat["f3_copper_ret"] = 0.50 * ret_hg1 + 0.50 * ret_lme

    ndf_pts_rel = (df_clean["CHN1M Curncy|PX_LAST"].diff() / df_clean["USDCLP Curncy|PX_LAST"]) * 100.0
    ndf_yld_diff = df_clean["CHNI1M Curncy|PX_LAST"].diff()
    raw_feat["f4_ndf_pressure"] = 0.50 * ndf_pts_rel + 0.50 * ndf_yld_diff

    spread_2y = df_clean["CHSWP2 Curncy|PX_LAST"] - df_clean["USGG2YR Index|PX_LAST"]
    raw_feat["f5_rate_spread_2y"] = spread_2y.diff(5)

    sma50 = df_clean["USDCLP Curncy|PX_LAST"].rolling(50).mean()
    raw_feat["f6_trend_sma50"] = (df_clean["USDCLP Curncy|PX_LAST"] / sma50) - 1.0

    mom_20d = ret_spot_log.rolling(20).sum()
    rv_20d = ret_spot_log.rolling(20).std()

    # Insumo de hoy (cierre más reciente) para predecir mañana
    X_today = raw_feat.iloc[[-1]].to_numpy()
    last_date = df_clean["fecha"].iloc[-1].strftime("%Y-%m-%d")
    last_spot = float(df_clean["USDCLP Curncy|PX_LAST"].iloc[-1])
    carry_1d_val = float(r_clp_1d.iloc[-1] - r_usd_1d.iloc[-1])
    rv_daily_val = float(rv_20d.iloc[-1])
    trend_val = float(raw_feat["f6_trend_sma50"].iloc[-1])
    mom_val = float(mom_20d.iloc[-1])

    # Matriz histórica desfasada estrictamente con .shift(1)
    X_hist = raw_feat.shift(1).iloc[:-1]
    y_hist = target_y.iloc[:-1]
    ret_hist = df_clean["USDCLP Curncy|PX_LAST"].pct_change().iloc[:-1]

    valid_mask = X_hist.notna().all(axis=1) & y_hist.notna() & ret_hist.notna()
    X_train_full = X_hist[valid_mask].to_numpy()
    y_train_full = y_hist[valid_mask].to_numpy()
    ret_train_full = ret_hist[valid_mask].to_numpy()

    # Ensamble Dual (Estructural 2500d + Adaptativo 504d)
    s_long = max(0, len(X_train_full) - 2500)
    sc_long = PureRobustScaler()
    X_tr_l_sc = np.clip(sc_long.fit_transform(X_train_full[s_long:]), -3.5, 3.5)
    X_today_l_sc = np.clip(sc_long.transform(X_today), -3.5, 3.5)
    clf_long = BalancedWeightedL2Logistic(reg_lambda=REG_LAMBDA).fit(
        X_tr_l_sc, y_train_full[s_long:], sample_weight=np.abs(ret_train_full[s_long:]) + 1e-4
    )

    s_short = max(0, len(X_train_full) - 504)
    sc_short = PureRobustScaler()
    X_tr_s_sc = np.clip(sc_short.fit_transform(X_train_full[s_short:]), -3.5, 3.5)
    X_today_s_sc = np.clip(sc_short.transform(X_today), -3.5, 3.5)
    clf_short = BalancedWeightedL2Logistic(reg_lambda=REG_LAMBDA).fit(
        X_tr_s_sc, y_train_full[s_short:], sample_weight=np.abs(ret_train_full[s_short:]) + 1e-4
    )

    p_raw = float(0.55 * clf_long.predict_proba(X_today_l_sc)[0, 1] + 0.45 * clf_short.predict_proba(X_today_s_sc)[0, 1])

    # Módulo de Convicción y Filtro SMA50
    safe_vol = np.clip(rv_daily_val, 0.004, 0.020)
    carry_pen = np.clip(0.15 * (carry_1d_val / safe_vol), -0.012, 0.012)
    p_eff = float(np.clip(p_raw - carry_pen, 0.01, 0.99))

    # Umbrales calibrados
    ql3, ql1, qh1, qh3 = 0.440, 0.468, 0.532, 0.560

    if p_eff >= qh3:
        exp = 3
    elif p_eff >= qh1:
        exp = 1
    elif p_eff <= ql3:
        exp = -3
    elif p_eff <= ql1:
        exp = -1
    else:
        exp = 0

    # Filtro de Régimen de Tendencia
    if trend_val > 0.0:
        if exp == -3:
            exp = -1
        if exp < 0 and (trend_val > 0.012 or mom_val > 0.012):
            exp = 0
    else:
        if exp == 3:
            exp = 1
        if exp > 0 and (trend_val < -0.015 and mom_val < -0.015) and carry_1d_val > 0:
            exp = 0

    if exp > 0:
        dir_str = "SUBE (Compra USD / Paga Carry)"
    elif exp < 0:
        dir_str = "BAJA (Venta Corta USD / Recibe Carry)"
    else:
        dir_str = "ABSTENCIÓN (En Pesos Chilenos ganando tasa r_CLP)"

    # Formato de salida requerido por las bases
    result = {
        "fecha_cierre_t1": last_date,
        "ultimo_spot_usdclp": last_spot,
        "probabilidad_estimada": round(p_raw, 4),
        "probabilidad_efectiva_carry": round(p_eff, 4),
        "carry_diario_bps": round(carry_1d_val * 10000.0, 2),
        "posicion_sugerida": int(exp),
        "direccion_esperada": dir_str,
        "status": "SUCCESS"
    }

    print("\n" + "=" * 70)
    print("TORNEO BANCO ITAÚ & FEN — ENTREGABLE 1: SEÑAL DEL DÍA")
    print("=" * 70)
    print(f"Fecha Insumo (t-1)         : {result['fecha_cierre_t1']}")
    print(f"Cierre Spot USD/CLP        : {result['ultimo_spot_usdclp']:.2f}")
    print(f"Probabilidad P(Sube)       : {result['probabilidad_estimada']*100:.2f}%")
    print(f"Costo Carry Estimado       : {result['carry_diario_bps']:+.2f} bps/día")
    print(f"Dirección Esperada         : {result['direccion_esperada']}")
    print(f"POSICIÓN SUGERIDA (t)      : {result['posicion_sugerida']:+d}x")
    print("=" * 70)

    # Exportar a JSON para el sistema de evaluación del laboratorio
    out_json = "senal_del_dia.json"
    with open(out_json, "w", encoding="utf-8") as f:
        json.dump(result, f, indent=4, ensure_ascii=False)
    print(f"Archivo exportado: '{out_json}'")


if __name__ == "__main__":
    # parser.parse_known_args() ignora los argumentos internos de Colab/Jupyter
    parser = argparse.ArgumentParser(description="Generador diario de señal USD/CLP")
    parser.add_argument("--file", type=str, default=DEFAULT_DATA_FILE, help="Ruta a base_usdclp.xlsx")
    args, unknown = parser.parse_known_args()
    run_daily_inference(args.file)