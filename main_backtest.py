class PureRobustScaler:
    """Escalador estadístico robusto basado en mediana y rango intercuartílico (IQR)."""
    def __init__(self):
        self.median_ = None
        self.iqr_ = None

    def fit(self, X: np.ndarray):
        self.median_ = np.median(X, axis=0)
        q75 = np.percentile(X, 75, axis=0)
        q25 = np.percentile(X, 25, axis=0)
        iqr = q75 - q25
        iqr[iqr <= 1e-12] = 1.0
        self.iqr_ = iqr
        return self

    def transform(self, X: np.ndarray) -> np.ndarray:
        return (X - self.median_) / self.iqr_

    def fit_transform(self, X: np.ndarray) -> np.ndarray:
        return self.fit(X).transform(X)


class BalancedWeightedL2Logistic:
    """
    Regresión Logística con penalización L2 optimizada vía L-BFGS-B (SciPy).
    Incorpora:
    - Sample Weighting por atribución absoluta de retorno |r_t| (López de Prado, 2018).
    - Balanceo exacto de masa de clases (0.50 alcista / 0.50 bajista) para garantizar
      que la probabilidad predicha esté perfectamente calibrada en torno a 0.50.
    """
    def __init__(self, reg_lambda: float = 0.22):
        self.reg_lambda = reg_lambda
        self.weights_ = None
        self.bias_ = 0.0

    def fit(self, X: np.ndarray, y: np.ndarray, sample_weight: np.ndarray = None):
        n_samples, n_features = X.shape
        if sample_weight is None:
            w_raw = np.ones(n_samples, dtype=float)
        else:
            w_raw = np.asarray(sample_weight, dtype=float).copy()

        # Balancear masa total de clase positiva (y=1) y negativa (y=0) en 0.50 cada una
        pos_mask = (y == 1)
        neg_mask = (y == 0)
        w_s = np.zeros(n_samples, dtype=float)
        if np.any(pos_mask) and np.any(neg_mask):
            w_s[pos_mask] = 0.50 * w_raw[pos_mask] / np.sum(w_raw[pos_mask])
            w_s[neg_mask] = 0.50 * w_raw[neg_mask] / np.sum(w_raw[neg_mask])
        else:
            w_s = w_raw / np.sum(w_raw)

        def objective(params):
            w = params[:-1]
            b = params[-1]
            z = np.clip(X @ w + b, -20.0, 20.0)
            loss = np.sum(w_s * (np.logaddexp(0.0, z) - y * z))
            reg = 0.5 * self.reg_lambda * np.sum(w ** 2)
            return loss + reg

        def gradient(params):
            w = params[:-1]
            b = params[-1]
            z = np.clip(X @ w + b, -20.0, 20.0)
            p = 1.0 / (1.0 + np.exp(-z))
            err = w_s * (p - y)
            grad_w = X.T @ err + self.reg_lambda * w
            grad_b = np.sum(err)
            return np.append(grad_w, grad_b)

        init_params = np.zeros(n_features + 1)
        res = minimize(
            objective, init_params, jac=gradient, method="L-BFGS-B",
            options={"maxiter": 250, "ftol": 1e-8}
        )
        self.weights_ = res.x[:-1]
        self.bias_ = res.x[-1]
        return self

    def predict_proba(self, X: np.ndarray) -> np.ndarray:
        z = np.clip(X @ self.weights_ + self.bias_, -20.0, 20.0)
        p1 = 1.0 / (1.0 + np.exp(-z))
        return np.column_stack([1.0 - p1, p1])


def pure_roc_auc_score(y_true: np.ndarray, y_score: np.ndarray) -> float:
    """Cálculo exacto de ROC-AUC mediante estadístico de rangos de Wilcoxon-Mann-Whitney."""
    idx = np.argsort(y_score)
    y_sorted = y_true[idx]
    n_pos = int(np.sum(y_true == 1))
    n_neg = len(y_true) - n_pos
    if n_pos == 0 or n_neg == 0:
        return 0.50
    ranks = np.arange(1, len(y_true) + 1, dtype=float)
    rank_sum_pos = np.sum(ranks[y_sorted == 1])
    return (rank_sum_pos - n_pos * (n_pos + 1.0) / 2.0) / (n_pos * n_neg)


