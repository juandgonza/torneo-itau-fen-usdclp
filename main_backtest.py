# 4. BACKTESTING ECONÓMICO Y TABLA DE MÉTRICAS CORREGIDA
# =============================================================================
def run_backtest(df_oos: pd.DataFrame, cost_bps: float = 1.5) -> pd.DataFrame:
    print("[4/6] Contabilizando P&L neto de Carry y Costos de Transacción...")
    bt = df_oos.copy()
    cost_dec = cost_bps / 10000.0

    exp = bt["exposicion"].to_numpy()
    ret_spot = bt["ret_usdclp_simple"].to_numpy()
    r_clp = bt["r_clp_t1"].to_numpy()
    carry_diff = bt["carry_diff_t1"].to_numpy()  # r_CLP - r_USD

    # Rotación diaria |Exposicion_t - Exposicion_{t-1}|
    delta_exp = np.abs(np.diff(exp, prepend=0))
    bt["turnover"] = delta_exp
    bt["tx_cost"] = cost_dec * delta_exp

    # Carry de la posición: Comprar USD (+1, +3) paga (r_CLP - r_USD); Corto (-1, -3) lo recibe
    bt["carry_spread_pos"] = -exp * carry_diff

    # Exceso de retorno sobre la tasa local libre de riesgo (CLP Cash)
    bt["strat_excess_gross"] = exp * ret_spot + bt["carry_spread_pos"]
    bt["strat_excess_net"] = bt["strat_excess_gross"] - bt["tx_cost"]

    # Retorno Total de la estrategia (cuando Exp = 0, el capital gana r_CLP local sin costos)
    bt["strat_total_gross"] = r_clp + bt["strat_excess_gross"]
    bt["strat_total_net"] = r_clp + bt["strat_excess_net"]

    # Referencia 1: Comprar siempre (+1x con Carry)
    bt["bench_always_long1_excess"] = 1.0 * ret_spot - 1.0 * carry_diff
    bt["bench_always_long1_total"] = r_clp + bt["bench_always_long1_excess"]

    # Referencia 2: No operar nunca (Tasa Local CLP, Exposición 0 constante)
    bt["bench_never_trade_excess"] = np.zeros(len(bt))
    bt["bench_never_trade_total"] = r_clp

    # Curvas acumuladas en Base 100
    bt["cum_strat_net"] = 100.0 * np.cumprod(1.0 + bt["strat_total_net"])
    bt["cum_strat_gross"] = 100.0 * np.cumprod(1.0 + bt["strat_total_gross"])
    bt["cum_bench_long1"] = 100.0 * np.cumprod(1.0 + bt["bench_always_long1_total"])
    bt["cum_bench_cash_clp"] = 100.0 * np.cumprod(1.0 + bt["bench_never_trade_total"])

    running_max = bt["cum_strat_net"].cummax()
    bt["drawdown_pct"] = (bt["cum_strat_net"] / running_max - 1.0) * 100.0
    return bt


def compute_performance_metrics(
    daily_total_ret: np.ndarray,
    daily_excess_ret: np.ndarray,
    exposures: np.ndarray,
    name: str
) -> dict:
    """Calcula métricas anualizadas corrigiendo el cálculo de Hit Ratio sobre días con posición != 0."""
    years = len(daily_total_ret) / 252.0
    cum_total = np.prod(1.0 + daily_total_ret) - 1.0
    cagr_total = (1.0 + cum_total) ** (1.0 / years) - 1.0

    ann_excess = np.mean(daily_excess_ret) * 252.0
    ann_vol = np.std(daily_excess_ret, ddof=1) * np.sqrt(252.0)
    sharpe = ann_excess / ann_vol if ann_vol > 1e-8 else 0.0

    downside = np.minimum(daily_excess_ret, 0.0)
    downside_vol = np.sqrt(np.mean(downside ** 2)) * np.sqrt(252.0)
    sortino = ann_excess / downside_vol if downside_vol > 1e-8 else 0.0

    wealth = 100.0 * np.cumprod(1.0 + daily_total_ret)
    dd = wealth / np.maximum.accumulate(wealth) - 1.0
    max_dd = np.min(dd)
    calmar = cagr_total / abs(max_dd) if abs(max_dd) > 1e-8 else 0.0

    # Hit Ratio evaluado estrictamente en las jornadas donde se tomó exposición cambiaria (!= 0)
    active_mask = (exposures != 0)
    hit_ratio = np.mean(daily_excess_ret[active_mask] > 0) * 100.0 if np.any(active_mask) else 0.0
    abstain_pct = np.mean(exposures == 0) * 100.0

    return {
        "Estrategia": name,
        "Ret. Acum. Total (%)": cum_total * 100.0,
        "CAGR Total (%)": cagr_total * 100.0,
        "Volatilidad Anual (%)": ann_vol * 100.0,
        "Sharpe Ratio (Exceso)": sharpe,
        "Sortino Ratio": sortino,
        "Max Drawdown (%)": max_dd * 100.0,
        "Calmar Ratio": calmar,
        "Hit Ratio Activo (%)": hit_ratio,
        "% Abstención (Exp=0)": abstain_pct,
    }


