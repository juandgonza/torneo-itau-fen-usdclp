def build_six_core_features(df: pd.DataFrame):
    """
    Construye exclusivamente los 6 factores con fundamento económico y asincronía
    horaria legítima (cierre NY 17:00 ET vs cierre SCL 13:30 en t-1), todos
    estrictamente estacionarios y desfasados con .shift(1).
    """
    print("[2/6] Construyendo los 6 Factores Clave y devengo de Carry con .shift(1) estricto...")
    data = pd.DataFrame(index=df.index)
    data["fecha"] = df["fecha"]
    data["usdclp"] = df["USDCLP Curncy|PX_LAST"]

    # Target y Retorno en jornada t
    ret_spot_log = np.log(df["USDCLP Curncy|PX_LAST"] / df["USDCLP Curncy|PX_LAST"].shift(1))
    data["ret_usdclp_log"] = ret_spot_log
    data["ret_usdclp_simple"] = df["USDCLP Curncy|PX_LAST"].pct_change()
    data["target_y"] = (df["USDCLP Curncy|PX_LAST"] > df["USDCLP Curncy|PX_LAST"].shift(1)).astype(int)

    # -------------------------------------------------------------------------
    # A. TASAS OVERNIGHT Y CARRY (CONOCIDAS EN t-1)
    # -------------------------------------------------------------------------
    delta_days = df["fecha"].diff().dt.days.clip(lower=1, upper=7).fillna(1.0)

    # Tasa overnight CLP desde variación diaria del índice CLICP dividida por días calendario
    icp_raw_ret = df["CLICP Index|PX_LAST"].pct_change() / delta_days
    tpm_daily = (df["CHOVCHOV Index|PX_LAST"] / 100.0) / 360.0
    r_clp_1d = pd.Series(
        np.where((icp_raw_ret > 0) & (icp_raw_ret < 0.002), icp_raw_ret, tpm_daily),
        index=df.index
    )

    # Tasa overnight USD empalmando SOFRRATE (desde 2018) con FEDL01 (Fed Funds)
    usd_rate_annual = df["SOFRRATE Index|PX_LAST"].combine_first(df["FEDL01 Index|PX_LAST"])
    r_usd_1d = (usd_rate_annual / 100.0) / 360.0

    # Desfase estricto .shift(1) para contabilidad de P&L (escalado por días de tenencia)
    holding_days = delta_days.shift(1).fillna(1.0)
    data["r_clp_t1"] = r_clp_1d.shift(1) * holding_days
    data["r_usd_t1"] = r_usd_1d.shift(1) * holding_days
    data["carry_diff_t1"] = data["r_clp_t1"] - data["r_usd_t1"]

    # Tasa diaria pura (1 día, sin distorsión por fin de semana) para el módulo de convicción
    data["carry_1d_t1"] = (r_clp_1d - r_usd_1d).shift(1)

    # -------------------------------------------------------------------------
    # B. LOS 6 FACTORES PREDICTIVOS (CALCULADOS EN s Y DESFASADOS CON .shift(1))
    # -------------------------------------------------------------------------
    raw_feat = pd.DataFrame(index=df.index)

    # FACTOR 1: Divergencia Lead-Lag FX Emergente (NY 17:00 ET vs SCL 13:30)
    ret_zar = np.log(df["USDZAR Curncy|PX_LAST"] / df["USDZAR Curncy|PX_LAST"].shift(1))
    ret_mxn = np.log(df["USDMXN Curncy|PX_LAST"] / df["USDMXN Curncy|PX_LAST"].shift(1))
    ret_brl = np.log(df["USDBRL Curncy|PX_LAST"] / df["USDBRL Curncy|PX_LAST"].shift(1))
    em_basket = 0.40 * ret_zar + 0.35 * ret_mxn + 0.25 * ret_brl
    raw_feat["f1_em_divergence"] = em_basket - 0.35 * ret_spot_log

    # FACTOR 2: Divergencia Dólar Global (BBDXY y DXY al cierre NY vs USD/CLP local)
    ret_bbdxy = np.log(df["BBDXY Index|PX_LAST"] / df["BBDXY Index|PX_LAST"].shift(1))
    ret_dxy = np.log(df["DXY Curncy|PX_LAST"] / df["DXY Curncy|PX_LAST"].shift(1))
    usd_global = 0.60 * ret_bbdxy + 0.40 * ret_dxy
    raw_feat["f2_usd_divergence"] = usd_global - 0.35 * ret_spot_log

    # FACTOR 3: Cobre Ponderado (COMEX HG1 + LME 3M LMCADS03)
    ret_hg1 = np.log(df["HG1 Comdty|PX_LAST"] / df["HG1 Comdty|PX_LAST"].shift(1))
    ret_lme = np.log(df["LMCADS03 Comdty|PX_LAST"] / df["LMCADS03 Comdty|PX_LAST"].shift(1))
    raw_feat["f3_copper_ret"] = 0.50 * ret_hg1 + 0.50 * ret_lme

    # FACTOR 4: Presión en Puntos NDF 1M y Yield Implícito Offshore (17:00 ET)
    ndf_pts_rel = (df["CHN1M Curncy|PX_LAST"].diff() / df["USDCLP Curncy|PX_LAST"]) * 100.0
    ndf_yld_diff = df["CHNI1M Curncy|PX_LAST"].diff()
    raw_feat["f4_ndf_pressure"] = 0.50 * ndf_pts_rel + 0.50 * ndf_yld_diff

    # FACTOR 5: Diferencial de Tasas 2Y (Swap Cámara 2Y CHSWP2 - US Treasury 2Y USGG2YR)
    spread_2y = df["CHSWP2 Curncy|PX_LAST"] - df["USGG2YR Index|PX_LAST"]
    raw_feat["f5_rate_spread_2y"] = spread_2y.diff(5)

    # FACTOR 6: Régimen de Tendencia (Distancia porcentual del Spot a su SMA de 50 días)
    sma50 = df["USDCLP Curncy|PX_LAST"].rolling(50).mean()
    raw_feat["f6_trend_sma50"] = (df["USDCLP Curncy|PX_LAST"] / sma50) - 1.0

    # Variables de Estado para el Overlay de Régimen y Riesgo (todas desfasadas en t-1)
    mom_20d = ret_spot_log.rolling(20).sum()
    rv_20d = ret_spot_log.rolling(20).std()

    # Guardar última fila sin shift (día T final) para emitir la "Señal del Día" (T+1)
    X_unshifted_last = raw_feat.iloc[[-1]].copy()
    state_last = {
        "trend_sma50": float(raw_feat["f6_trend_sma50"].iloc[-1]),
        "mom_20d": float(mom_20d.iloc[-1]),
        "rv_20d": float(rv_20d.iloc[-1]),
        "carry_1d": float(r_clp_1d.iloc[-1] - r_usd_1d.iloc[-1]),
    }

    # APLICAR DESFASE ESTRICTO .shift(1) A TODA LA MATRIZ PREDICTIVA X
    X_lagged = raw_feat.shift(1)
    feature_names = list(X_lagged.columns)
    for col in feature_names:
        data[col] = X_lagged[col]

    data["trend_sma50_t1"] = raw_feat["f6_trend_sma50"].shift(1)
    data["mom_20d_t1"] = mom_20d.shift(1)
    data["rv_20d_t1"] = rv_20d.shift(1)

    valid_cols = feature_names + ["ret_usdclp_simple", "r_clp_t1", "carry_1d_t1", "rv_20d_t1", "mom_20d_t1"]
    data_clean = data.dropna(subset=valid_cols).copy().reset_index(drop=True)

    print(f"      -> Matriz X_{{t-1}} depurada: {len(feature_names)} factores clave.")
    print(f"      -> Observaciones válidas: {len(data_clean)} "
          f"({data_clean['fecha'].min().strftime('%Y-%m-%d')} a {data_clean['fecha'].max().strftime('%Y-%m-%d')}).")
    return data_clean, feature_names, X_unshifted_last, state_last


