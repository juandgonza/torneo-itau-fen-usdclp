# 5. PRUEBAS ESTADÍSTICAS: DIEBOLD-MARIANO (HLN-HAC) Y BLOCK BOOTSTRAP
# =============================================================================
def diebold_mariano_test(y_true: np.ndarray, p_model: np.ndarray, p_bench: np.ndarray, h: int = 1):
    """
    Test de Diebold-Mariano con corrección de muestras finitas de Harvey, Leybourne &
    Newbold (1997) y varianza HAC Newey-West sobre pérdida cuadrática (Brier Score).
    Un estadístico DM < 0 indica que el modelo tiene menor error de pronóstico que el benchmark.
    """
    T = len(y_true)
    loss_model = (y_true - p_model) ** 2
    loss_bench = (y_true - p_bench) ** 2
    d_t = loss_model - loss_bench
    d_bar = np.mean(d_t)
    d_centered = d_t - d_bar

    max_lag = max(h - 1, int(np.floor(4.0 * (T / 100.0) ** (2.0 / 9.0))))
    lrv = np.sum(d_centered ** 2) / T
    for k in range(1, max_lag + 1):
        weight = 1.0 - k / (max_lag + 1.0)
        gamma_k = np.sum(d_centered[k:] * d_centered[:-k]) / T
        lrv += 2.0 * weight * gamma_k

    lrv = max(lrv, 1e-12)
    dm_raw = d_bar / np.sqrt(lrv / T)
    hln_factor = np.sqrt((T + 1.0 - 2.0 * h + (h * (h - 1.0)) / T) / T)
    dm_stat = dm_raw * hln_factor

    p_val_one_sided = stats.t.cdf(dm_stat, df=T - 1)
    return {
        "dm_stat": dm_stat,
        "p_value_one_sided": p_val_one_sided,
        "brier_model": np.mean(loss_model),
        "brier_bench": np.mean(loss_bench),
    }


def nonparametric_bootstrap_test(
    strat_ret: np.ndarray,
    bench_ret: np.ndarray,
    n_boot: int = 10000,
    block_length: int = 5,
    seed: int = 42
):
    """Circular Block Bootstrap (10,000 réplicas) sobre el diferencial de retorno y Sharpe."""
    rng = np.random.default_rng(seed)
    T = len(strat_ret)
    diff_ret = strat_ret - bench_ret
    obs_ann_alpha = np.mean(diff_ret) * 252.0 * 100.0

    n_blocks = int(np.ceil(T / block_length))
    start_points = rng.integers(0, T, size=(n_boot, n_blocks))
    offsets = np.arange(block_length)
    block_indices = (start_points[:, :, None] + offsets[None, None, :]).reshape(n_boot, -1)[:, :T] % T

    boot_strat = strat_ret[block_indices]
    boot_bench = bench_ret[block_indices]
    boot_diff = boot_strat - boot_bench

    boot_alpha_dist = np.mean(boot_diff, axis=1) * 252.0 * 100.0
    pval_alpha = np.mean(boot_alpha_dist <= 0.0)
    ci_95_low, ci_95_high = np.percentile(boot_alpha_dist, [2.5, 97.5])

    sr_strat = (np.mean(boot_strat, axis=1) / (np.std(boot_strat, axis=1, ddof=1) + 1e-9)) * np.sqrt(252.0)
    sr_bench = (np.mean(boot_bench, axis=1) / (np.std(boot_bench, axis=1, ddof=1) + 1e-9)) * np.sqrt(252.0)
    pval_sharpe = np.mean((sr_strat - sr_bench) <= 0.0)

    return {
        "obs_ann_alpha_pct": obs_ann_alpha,
        "boot_alpha_dist": boot_alpha_dist,
        "pval_block": pval_alpha,
        "pval_sharpe": pval_sharpe,
        "ci_95_low": ci_95_low,
        "ci_95_high": ci_95_high,
    }


