def load_and_clean_data(filepath: str, sheet_name: str, start_date: str) -> pd.DataFrame:
    print("[1/6] Cargando y auditando base de datos Bloomberg...")
    xls = pd.ExcelFile(filepath)
    assert sheet_name in xls.sheet_names, f"Hoja '{sheet_name}' no encontrada en {xls.sheet_names}"

    df = pd.read_excel(filepath, sheet_name=sheet_name)
    df["fecha"] = pd.to_datetime(df["fecha"])
    df = df.sort_values("fecha").reset_index(drop=True)
    df = df[df["fecha"] >= start_date].copy().reset_index(drop=True)

    # Identificar cotizaciones reales de USD/CLP y eliminar feriados rancios
    has_usdclp = df["USDCLP Curncy|PX_LAST"].notna()
    price_diff = df["USDCLP Curncy|PX_LAST"].diff()
    intraday_range = df["USDCLP Curncy|PX_HIGH"] - df["USDCLP Curncy|PX_LOW"]
    is_stale_holiday = (price_diff == 0) & (intraday_range == 0)

    # Forward-fill defensivo (.ffill()) de series internacionales antes y después de filtrar
    cols_to_ffill = [c for c in df.columns if c != "fecha" and "FECHA_RELEASE" not in c]
    df[cols_to_ffill] = df[cols_to_ffill].ffill()

    df_clean = df[has_usdclp & (~is_stale_holiday)].copy().reset_index(drop=True)
    df_clean[cols_to_ffill] = df_clean[cols_to_ffill].ffill()

    print(f"      -> Muestra limpia: {len(df_clean)} jornadas hábiles "
          f"({df_clean['fecha'].min().strftime('%Y-%m-%d')} a {df_clean['fecha'].max().strftime('%Y-%m-%d')}).")
    return df_clean


